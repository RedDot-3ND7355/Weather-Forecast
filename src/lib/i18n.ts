const MESSAGES: Record<Locale, Record<keyof typeof EN, string>> = { en: EN, fr: FR };

export type MsgKey = keyof typeof EN;

export function detectLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  const lang = (navigator.languages?.[0] || navigator.language || "en").toLowerCase();
  return lang.startsWith("fr") ? "fr" : "en";
}

export function localeTag(locale: Locale): string {
  return locale === "fr" ? "fr-CA" : "en-CA";
}

export function t(
  locale: Locale,
  key: MsgKey,
  vars?: Record<string, string | number>,
): string {
  let s = MESSAGES[locale][key] ?? MESSAGES.en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export function useLocale(): Locale {
  return useWeatherStore((s) => s.locale);
}

export function useT() {
  const locale = useLocale();
  return {
    locale,
    t: (key: MsgKey, vars?: Record<string, string | number>) => t(locale, key, vars),
  };
}
